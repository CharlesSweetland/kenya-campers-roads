"""Build data/roads.geojson from data/roads-src.json.

Each road is routed along real OpenStreetMap roads through its waypoints using the public
OSRM demo server (router.project-osrm.org, fair use: one request per road, run occasionally).
A road with a "gpx" file uses that track instead.

    python tools/build_roads.py             # rebuild every road
    python tools/build_roads.py namanga-meshanani kimana-chyulu-gate   # rebuild some, keep the rest
    python tools/build_roads.py --src other-src.json --out other.geojson  # different files

Uses only the Python standard library. Prints a warning when a route is much longer than the
straight line between its waypoints, which usually means it took a detour: add a via point.
"""
import json
import math
import sys
import time
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "roads-src.json"
OUT = ROOT / "data" / "roads.geojson"
OSRM = "https://router.project-osrm.org/route/v1/driving/{coords}?overview=full&geometries=geojson"
UA = {"User-Agent": "kenya-road-reports-build/0.2"}
TOLERANCE = 0.0002   # simplification tolerance in degrees (~20 m)
DETOUR_RATIO = 1.8


def haversine_km(a, b):
    lat1, lon1, lat2, lon2 = map(math.radians, (a[0], a[1], b[0], b[1]))
    h = math.sin((lat2 - lat1) / 2) ** 2 + math.cos(lat1) * math.cos(lat2) * math.sin((lon2 - lon1) / 2) ** 2
    return 6371 * 2 * math.asin(math.sqrt(h))


def simplify(points, tol):
    """Douglas-Peucker on [lon, lat] points."""
    if len(points) < 3:
        return points
    (x1, y1), (x2, y2) = points[0], points[-1]
    dx, dy = x2 - x1, y2 - y1
    norm = math.hypot(dx, dy) or 1e-12
    dmax, idx = 0.0, 0
    for i in range(1, len(points) - 1):
        x0, y0 = points[i]
        d = abs(dy * x0 - dx * y0 + x2 * y1 - y2 * x1) / norm
        if d > dmax:
            dmax, idx = d, i
    if dmax <= tol:
        return [points[0], points[-1]]
    return simplify(points[: idx + 1], tol)[:-1] + simplify(points[idx:], tol)


def route_osrm(waypoints):
    coords = ";".join(f"{lon},{lat}" for lat, lon in waypoints)
    req = urllib.request.Request(OSRM.format(coords=coords), headers=UA)
    with urllib.request.urlopen(req, timeout=60) as r:
        data = json.load(r)
    if data.get("code") != "Ok":
        raise RuntimeError(data.get("message") or data.get("code"))
    route = data["routes"][0]
    return route["geometry"]["coordinates"], route["distance"] / 1000


def read_gpx(path):
    ns = {"g": "http://www.topografix.com/GPX/1/1"}
    root = ET.parse(path).getroot()
    pts = root.findall(".//g:trkpt", ns) or root.findall(".//g:rtept", ns) or root.findall(".//trkpt")
    coords = [[float(p.get("lon")), float(p.get("lat"))] for p in pts]
    km = sum(haversine_km((a[1], a[0]), (b[1], b[0])) for a, b in zip(coords, coords[1:]))
    return coords, km


def main(only):
    src = json.loads(SRC.read_text(encoding="utf-8"))
    old = {}
    if OUT.exists():
        old = {f["properties"]["id"]: f for f in json.loads(OUT.read_text(encoding="utf-8"))["features"]}

    features = []
    for road in src["roads"]:
        rid = road["id"]
        props = {k: road[k] for k in ("id", "name", "region", "surface") if k in road}
        if only and rid not in only and rid in old:
            f = old[rid]
            f["properties"] = {**f["properties"], **props}
            features.append(f)
            continue
        try:
            if road.get("gpx"):
                coords, km = read_gpx(SRC.parent / road["gpx"])
                props["source"] = "gpx"
            else:
                coords, km = route_osrm(road["waypoints"])
                props["source"] = "osm"
                straight = sum(haversine_km(a, b) for a, b in zip(road["waypoints"], road["waypoints"][1:]))
                if km > straight * DETOUR_RATIO:
                    print(f"  ! {rid}: route is {km:.0f} km vs {straight:.0f} km straight. Check it, maybe add a via point.")
                time.sleep(1)
        except Exception as e:  # keep the old geometry rather than lose the road
            print(f"  ! {rid}: {e}. Keeping previous geometry.")
            if rid in old:
                features.append(old[rid])
            continue
        line = [[round(x, 5), round(y, 5)] for x, y in simplify(coords, TOLERANCE)]
        props["length_km"] = round(km)
        features.append({"type": "Feature", "properties": props, "geometry": {"type": "LineString", "coordinates": line}})
        print(f"  {rid}: {km:.0f} km, {len(line)} points")

    out = {
        "type": "FeatureCollection",
        "_note": "Generated by tools/build_roads.py from data/roads-src.json. Edit that file, not this one. "
                 "Road geometry © OpenStreetMap contributors (ODbL), routed with OSRM.",
        "features": features,
    }
    OUT.write_text(json.dumps(out, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print(f"Wrote {OUT} with {len(features)} roads.")


if __name__ == "__main__":
    args = sys.argv[1:]
    for flag in ("--src", "--out"):
        if flag in args:
            i = args.index(flag)
            path = Path(args[i + 1]).resolve()
            if flag == "--src":
                SRC = path
            else:
                OUT = path
            del args[i:i + 2]
    main(set(args))
